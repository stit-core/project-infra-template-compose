#!/usr/bin/env bash
# Render-time config assembly:
#   1. envsubst для не-vault `.tpl` файлов (configs/**/*.tpl, кроме vault-agent/templates/).
#   2. Сборка configs/vault-agent/agent.hcl из agent.hcl.parts/ под активный
#      COMPOSE_PROFILES.
#   3. Генерация .runtime/configs/vault-health.sh — script для healthcheck
#      vault-agent'а, проверяет non-empty всех expected output'ов под активный
#      profile-набор.
#
# configs/vault-agent/templates/ исключаются из envsubst: эти .tpl читаются
# vault-agent'ом напрямую (consul-template syntax {{ with secret ... }});
# envsubst здесь только засрёт директорию orphan-копиями.
set -euo pipefail
cd "$(dirname "$0")/.."

if [ ! -f .env ]; then
  echo "ERR: .env не найден" >&2
  exit 1
fi

set -a
# shellcheck disable=SC1091
. ./.env
set +a

# Managed-дефолт адреса корп Vault для envsubst head.hcl (self-hosted задаёт
# свой VAULT_ADDR в .env). Только эта переменная подставляется в agent.hcl.
export VAULT_ADDR="${VAULT_ADDR:-https://vault.stit.tech}"

# ───── 1. envsubst для не-vault .tpl ─────
while IFS= read -r tpl; do
  out="${tpl%.tpl}"
  envsubst < "$tpl" > "$out"
  echo "rendered $out"
done < <(find configs -type f -name '*.tpl' -not -path 'configs/vault-agent/*')

# ───── 2. agent.hcl сборка из parts/ ─────
parts=configs/vault-agent/agent.hcl.parts
out=configs/vault-agent/agent.hcl

active_profiles=()
IFS=',' read -ra _p_arr <<<"${COMPOSE_PROFILES:-}"
declare -A _seen=()
for p in "${_p_arr[@]}"; do
  p="${p// /}"
  [ -z "$p" ] && continue
  [ -n "${_seen[$p]:-}" ] && continue
  _seen[$p]=1
  active_profiles+=("$p")
done

{
  # Только ${VAULT_ADDR} подставляется (allow-list), чтобы не задеть прочие
  # `$`-литералы в HCL; остальные parts копируются как есть.
  envsubst '${VAULT_ADDR}' < "$parts/head.hcl"
  for p in "${active_profiles[@]}"; do
    block="$parts/$p.hcl"
    [ -f "$block" ] || continue
    printf '\n'
    cat "$block"
  done
  printf '\n'
  cat "$parts/tail.hcl"
} > "$out"
echo "rendered $out (profiles: ${active_profiles[*]:-none})"

# ───── 3. vault-health.sh для healthcheck ─────
mkdir -p .runtime/configs
health=.runtime/configs/vault-health.sh
{
  echo '#!/bin/sh'
  echo '# Generated by scripts/render-configs.sh — проверяет все vault-agent'
  echo '# output-файлы под активный COMPOSE_PROFILES. Bind-mount в vault-agent,'
  echo '# используется в healthcheck (см. compose/vault-agent.yml).'
  echo 'set -e'
  echo '# always-on'
  echo 'test -s /configs/traefik.yml'
  for p in "${active_profiles[@]}"; do
    case "$p" in
      postgres) echo 'test -s /secrets/postgres.env' ;;
      backend)  echo 'test -s /secrets/backend.env'  ;;
      storage)  echo 'test -s /secrets/minio.env'; echo 'test -s /secrets/backup.env' ;;
    esac
  done
} > "$health"
chmod +x "$health"
echo "rendered $health"

# ───── 4. profile-snapshot для deploy.sh ─────
# deploy.sh использует .runtime/.profiles-prev чтобы детектить смену активных
# profile'ов между deploy'ами и trigger'ить force-recreate consumer'ов.
mkdir -p .runtime
printf '%s\n' "${active_profiles[@]}" | sort -u > .runtime/.profiles-cur
